#!/usr/bin/env python3
"""Compile original arithmetic domains from OCR leads; source mappings remain unaudited.

No source expression or answer is shipped. The app samples fresh operands from
digit/precision/zero-place constraints and keeps repeated operand relationships.
"""
import argparse,collections,hashlib,json
from fractions import Fraction
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]
def stable(value): return json.dumps(value,sort_keys=True,separators=(',',':'))
def short(value): return hashlib.sha256(stable(value).encode()).hexdigest()[:10]
def places(value):
 d=value.denominator;a=b=0
 while d%2==0: a+=1;d//=2
 while d%5==0: b+=1;d//=5
 return max(a,b) if d==1 else None
def compile_rows(rows):
 families={};mappings=[];unsupported=[]
 for row in rows:
  domains=[];bindings={}
  def node(tree):
   if tree['kind']=='literal':
    raw=tree['literal'];value=Fraction(raw)
    if raw not in bindings:
     integer,_,decimal=raw.partition('.');digits=len(integer);trailing=len(integer)-len(integer.rstrip('0')) if value and not decimal else 0
     domain={'digits':digits,'places':len(decimal),'belowOne':value<1,'trailingZeros':trailing}
     if value in (0,1):domain['fixed']=str(value)
     bindings[raw]=len(domains);domains.append(domain)
    return {'slot':bindings[raw]}
   return {'op':tree['operator'],'a':node(tree['left']),'b':node(tree['right'])}
  tree=node(row['operationTree']);answer=Fraction(row['evaluatedExactly']);answer_places=places(answer)
  if answer_places is None or answer_places>6:
   unsupported.append({'proposalId':row['proposalId'],'reason':'non-terminating or excessive answer precision'});continue
  props=row['operandDomain'];compound=props['operation']=='compound';decimal=any(d['places'] for d in domains)
  regroup=props.get('decimalColumnRegrouping',props.get('carrying',props.get('borrowing')))
  variant={'tree':tree,'domains':domains,'maxAnswerPlaces':max(answer_places,max(d['places'] for d in domains)),**({'regroup':regroup} if regroup is not None else {})}
  if compound:
   category='order-'+short(tree);title='Calculate with brackets and mixed operations';skills=['P5.S.WN.03' if row['level']>=5 else 'P3.S.AS.01']
  else:
   op=props['operation'];names={'+':'Add','-':'Subtract','×':'Multiply','÷':'Divide'}
   zeroes=max(d['trailingZeros'] for d in domains);digit=max(d['digits'] for d in domains)
   category=op+('-decimal' if decimal else '-whole')+(f'-zeros{zeroes}' if op in ('×','÷') and zeroes else '')+(f'-digits{digit}' if not decimal and not zeroes else '')+(f'-regroup{regroup}' if regroup is not None else '')
   title=names[op]+(' decimals' if decimal else ' whole numbers')+(' with regrouping' if regroup else '')
   if zeroes and op in ('×','÷'):title=names[op]+f" by multiples of {10**zeroes:,}"
   if decimal:skills=['P4.S.DEC.05' if op in ('+','-') else 'P5.S.DEC.01' if zeroes else 'P4.S.DEC.06']
   elif op in ('+','-'):skills=[f"P{min(row['level'],3)}.S.AS.01"]
   elif zeroes and row['level']>=5:skills=['P5.S.WN.02']
   elif op=='÷':skills=['P3.S.MD.04' if digit<=3 else 'P4.S.MD.03']
   else:skills=['P3.S.MD.03' if row['level']<=3 else 'P4.S.MD.01' if min(d['digits'] for d in domains)==1 else 'P4.S.MD.02']
  familykey=(row['level'],category);fid='a'+short(familykey)
  source={'paperId':row['paperId'],'sourceQuestion':str(row['questionNumber'])+(row.get('sourcePart') or ''),'sourcePage':row['sourcePages'][0]['page_number']}
  family=families.setdefault(familykey,{'id':fid,'level':row['level'],'title':title,'objective':'Calculate accurately using place value and the order of operations.','skillIds':skills,'canonicalPatternId':'arithmetic-'+category,'sourceUnits':[],'variants':[]})
  encoded=stable(variant);index=next((i for i,v in enumerate(family['variants']) if stable(v)==encoded),None)
  if index is None:index=len(family['variants']);family['variants'].append(variant)
  if source not in family['sourceUnits']:family['sourceUnits'].append(source)
  mappings.append({'proposalId':row['proposalId'],'paperId':row['paperId'],'sourceQuestion':source['sourceQuestion'],'sourcePage':source['sourcePage'],'familyId':fid,'variantIndex':index,'sourceMappingStatus':'unaudited','sourceCovered':False})
 return list(families.values()),mappings,unsupported
def main():
 p=argparse.ArgumentParser();p.add_argument('leads',type=Path);a=p.parse_args();rows=[json.loads(line) for line in a.leads.read_text().splitlines()]
 families,mappings,unsupported=compile_rows(rows)
 out=ROOT/'src/primary/paperImports/arithmeticTemplateData.ts'
 out.write_text("// Generated by scripts/compile-arithmetic-patterns.py. Original operand domains; source mapping unaudited.\nimport type {ArithmeticFamily} from './arithmeticTemplateTypes';\nexport const ARITHMETIC_FAMILIES:ArithmeticFamily[]="+json.dumps(families,ensure_ascii=False,separators=(',',':'))+';\n')
 report={'scope':'Implementation-first original arithmetic templates; not verified source coverage','sourceMappings':len(mappings),'sourcePapers':len({r['paperId'] for r in mappings}),'families':len(families),'variants':sum(len(f['variants']) for f in families),'byLevel':dict(collections.Counter(f['level'] for f in families)),'mappings':mappings,'unsupported':unsupported,'sourceAuditDeferred':True}
 (ROOT/'.generated/arithmetic-implementation-first.json').write_text(json.dumps(report,indent=2)+'\n')
 print(json.dumps({k:v for k,v in report.items() if k not in ('mappings','unsupported')}))
if __name__=='__main__':main()
